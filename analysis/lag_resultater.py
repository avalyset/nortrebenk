#!/usr/bin/env python3
"""Formats the tables in RESULTATER.md (AVVIK.md no. 11). Adds no statistic.

Reads the output of the locked analysis (results/p3_registrert.json, results/p3_med_tillegg.json), the run files in
data/p3/, data/sett_v1.jsonl and results/valutakurs.json, and writes results/tabeller.md. Every number in the tables is
copied from these files or counted from the run files. Two descriptive items were not pre-specified: cost in NOK and
the per-task table.

    python3 analysis/lag_resultater.py --hent-kurs        # fetch the Norges Bank rate into results/valutakurs.json
    python3 analysis/lag_resultater.py --B 66.71          # write results/tabeller.md

B (budget) is not in the repository; its source is the author's internal run log. It is used only to show the
arithmetic that gave the pass types.
"""
import argparse
import collections
import json
import pathlib
import time
import urllib.request

ROT = pathlib.Path(__file__).resolve().parent.parent
RES = ROT / "results"
P3 = ROT / "data" / "p3"
ARMER = ("claude-sonnet-5-5", "claude-opus-5-5")
VARIANTER = ("utvidet", "pr_tekst")
VNAVN = {"utvidet": "extended", "pr_tekst": "PR text"}
MARGIN = 1.5  # NTB-0014
KURS_URL = ("https://data.norges-bank.no/api/data/EXR/B.USD.NOK.SP?format=sdmx-json"
            "&startPeriod=2026-11-11&endPeriod=2026-11-17")


def jl(p):
    return [json.loads(l) for l in pathlib.Path(p).read_text(encoding="utf-8").splitlines() if l.strip()]


def hent_kurs():
    t = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    d = json.loads(urllib.request.urlopen(urllib.request.Request(KURS_URL, headers={"User-Agent": "nortrebenk-research/1.0"}),
                                          timeout=60).read())
    st = d["data"]["structure"]
    datoer = [v["id"] for v in st["dimensions"]["observation"][0]["values"]]
    obs = next(iter(d["data"]["dataSets"][0]["series"].values()))["observations"]
    siste = max(obs, key=int)
    ut = {"serie": "EXR/B.USD.NOK.SP", "enhet": "NOK per USD", "dato": datoer[int(siste)], "kurs": float(obs[siste][0]),
          "url": KURS_URL, "hentet_utc": t}
    if ut["dato"] != "2026-11-17":
        raise SystemExit(f"siste observasjon er {ut['dato']}, ikke 2026-11-17")
    (RES / "valutakurs.json").write_text(json.dumps(ut, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(ut, ensure_ascii=False))


def f4(x):
    return "–" if x is None else f"{x:.4f}"


def iv(x):
    return "–" if not x else f"[{x[0]:.4f}, {x[1]:.4f}]"


def tabell(hode, rader):
    ut = ["| " + " | ".join(hode) + " |", "|" + "|".join("---" for _ in hode) + "|"]
    ut += ["| " + " | ".join(str(c) for c in r) + " |" for r in rader]
    return ut


def kort(o):
    org, repo, nr = o.split("__")
    return f"{org}/{repo}#{nr}"


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--hent-kurs", action="store_true")
    a.add_argument("--B", type=float, default=None, help="budget B (source: the author's internal run log)")
    o = a.parse_args()
    if o.hent_kurs:
        hent_kurs(); return
    reg = json.loads((RES / "p3_registrert.json").read_text(encoding="utf-8"))
    til = json.loads((RES / "p3_med_tillegg.json").read_text(encoding="utf-8"))
    kurs = json.loads((RES / "valutakurs.json").read_text(encoding="utf-8"))
    kj, pas, tl = jl(P3 / "p3_kjoringer.jsonl"), jl(P3 / "p3_pass.jsonl"), jl(P3 / "p3_tillegg.jsonl")
    sett = jl(ROT / "data" / "sett_v1.jsonl")
    ider = sorted(r["id"].removeprefix("nortrebenk__") for r in sett)
    L = ["# Tables for RESULTATER.md", "",
         "Generated by `analysis/lag_resultater.py` from `results/p3_registrert.json`, `results/p3_med_tillegg.json`, "
         "`data/p3/`, `data/sett_v1.jsonl` and `results/valutakurs.json`. No new statistic.", ""]

    # 1. Passes
    L += ["## T1. Passes (data/p3/p3_pass.jsonl, data/p3/p3_kjoringer.jsonl)", ""]
    rader = []
    for p in pas:
        pr = [r for r in kj if r["pass"] == p["pass"]]
        st = collections.Counter(r["status"] for r in pr)
        planlagt = len({(r["oppgave"], r["arm"], r["tekstvariant"]) for r in pr})
        rader.append([p["pass"], p["type"], ", ".join(p["varianter"]), planlagt, st.get("gjennomfort", 0), st.get("manglende", 0),
                      st.get("forkastet", 0), "yes" if p["fullfort"] else "no", f"{p['kost']:.6f}", f"{p['kost_utvidet']:.6f}"])
    L += tabell(["pass", "type", "text variants", "planned runs", "completed", "missing", "discarded attempts", "completed pass",
                 "cost (USD)", "cost of extended part (USD)"], rader) + [""]
    brukt = sum(r.get("total_cost_usd") or 0 for r in kj)
    L += [f"Spent (sum of `total_cost_usd` over all rows in `data/p3/p3_kjoringer.jsonl`): {brukt:.6f} USD.", ""]

    # 2. Budget arithmetic
    if o.B is not None:
        L += ["## T2. Pass type after each completed pass (NTB-0014; B from the author's internal run log)", ""]
        rader = []
        for i, p in enumerate(pas):
            ferdige = pas[: i + 1]
            spent = sum(r.get("total_cost_usd") or 0 for r in kj if r["pass"] <= p["pass"])
            igjen = o.B - spent
            fulle = [x for x in ferdige if x["type"] == "fullt"]
            krav_full = MARGIN * max(x["kost"] for x in fulle)
            dyreste = max(ferdige, key=lambda x: x["kost"])
            krav_utv = MARGIN * dyreste["kost_utvidet"]
            neste = pas[i + 1]["type"] if i + 1 < len(pas) else "none (maximum of 3 passes reached)"
            rader.append([p["pass"], f"{spent:.6f}", f"{igjen:.6f}", f"1.5 × {max(x['kost'] for x in fulle):.6f} = {krav_full:.6f}",
                          f"1.5 × {dyreste['kost_utvidet']:.6f} (pass {dyreste['pass']}) = {krav_utv:.6f}", neste])
        L += tabell(["after pass", "spent (USD)", f"remaining of B = {o.B:.2f} (USD)", "needed for a full pass",
                     "needed for an extended-only pass", "next pass"], rader) + [""]

    # 3. Run-file counts
    g = [r for r in kj if r["status"] == "gjennomfort"]
    L += ["## T3. Counts from the run file (data/p3/p3_kjoringer.jsonl)", ""]
    L += tabell(["count", "value"], [
        ["rows", len(kj)],
        ["completed runs", len(g)],
        ["missing runs", sum(r["status"] == "manglende" for r in kj)],
        ["discarded attempts (status forkastet)", sum(r["status"] == "forkastet" for r in kj)],
        ["runs with `is_error` true", sum(bool(r.get("is_error")) for r in g)],
        ["runs that hit the budget cap", sum(bool(r.get("budsjettak_slo_inn")) for r in g)],
        ["runs that hit the time cap", sum(bool(r.get("tidstak_slo_inn")) for r in g)],
        ["runs with cost set to the cap", sum(bool(r.get("kostnad_satt_til_tak")) for r in g)],
        ["runs with attempt number above 1", sum((r.get("forsok") or 1) > 1 for r in g)],
        ["requests rejected by the proxy (sum of `mellomtjener_avvist`)", sum(r.get("mellomtjener_avvist") or 0 for r in g)],
        ["runs where agent changes to test files were discarded before grading (`forkastede_testfilendringer` > 0)",
         sum((r.get("forkastede_testfilendringer") or 0) > 0 for r in g)],
        ["Claude Code version (`claude_code`)", ", ".join(sorted({r.get("claude_code") for r in g}))],
    ]) + [""]

    # 4. Main measure and secondary measures
    h = reg["hovedtall"]["per_arm_og_variant"]
    L += ["## T4. Main measure (registered): solved share on the extended text (results/p3_registrert.json)", ""]
    L += tabell(["arm", "tasks", "runs", "solved runs", "solved share", "95 % interval, per task (eq. 3)",
                 "95 % interval, clustered on repository (eq. 4)"],
                [[a, h[f"{a}|utvidet"]["oppgaver"], h[f"{a}|utvidet"]["kjoringer"], h[f"{a}|utvidet"]["loste_kjoringer"],
                  f4(h[f"{a}|utvidet"]["loest_andel"]), iv(h[f"{a}|utvidet"]["intervall_per_oppgave"]),
                  iv(h[f"{a}|utvidet"]["intervall_klynget_repo"])] for a in ARMER]) + [""]
    L += ["## T5. Secondary measures (registered; results/p3_registrert.json)", ""]
    rader = []
    for a in ARMER:
        for v in VARIANTER:
            x = h[f"{a}|{v}"]
            rader.append([a, VNAVN[v], x["oppgaver"], x["kjoringer"], x["loste_kjoringer"], f4(x["loest_andel"]),
                          iv(x["intervall_per_oppgave"]), iv(x["intervall_klynget_repo"]), f4(x["kostnad_usd"]),
                          f4(x.get("kostnad_per_loste_usd")), f"{x['veggtid_s']['median']:.1f}",
                          f"{x['veggtid_s']['q1']:.1f}–{x['veggtid_s']['q3']:.1f}"])
    L += tabell(["arm", "text", "tasks", "runs", "solved runs", "solved share", "interval per task", "interval clustered",
                 "total cost (USD)", "cost per solved task (USD)", "wall time median (s)", "wall time quartiles (s)"], rader) + [""]
    L += ["## T6. Paired differences per task (registered, descriptive; results/p3_registrert.json)", ""]
    pd = reg["hovedtall"]["parvise_differanser"]
    rader = []
    for k, x in pd.items():
        rader.append([k.replace("|", ", "), x["oppgaver"], f4(x["differanse"]), iv(x["intervall_per_oppgave"]),
                      iv(x["intervall_klynget_repo"]), ", ".join(map(str, x.get("pass", []))) or "all completed passes with the text variant"])
    L += tabell(["difference", "tasks", "mean difference", "interval per task (eq. 7)", "interval clustered (eq. 8)", "passes"],
                rader) + [""]

    # 5. Breakdowns
    L += ["## T7. Breakdowns (registered; results/p3_registrert.json, field `inndelt`)", "",
          "Solved share per arm and text variant, with tasks and runs in parentheses.", ""]
    rader = []
    for grp, grupper in reg["inndelt"].items():
        for gnavn, x in grupper.items():
            pa = x["per_arm_og_variant"]
            celler = []
            for a in ARMER:
                for v in VARIANTER:
                    y = pa.get(f"{a}|{v}")
                    celler.append("–" if not y or y.get("loest_andel") is None else
                                  f"{y['loest_andel']:.4f} ({y['oppgaver']}; {y['kjoringer']})")
            uten = sum(pa[k]["oppgaver_uten_gjennomforte_kjoringer"]["antall"] for k in pa)
            rader.append([grp, gnavn, *celler, uten])
    L += tabell(["breakdown", "group", "Sonnet extended", "Sonnet PR text", "Opus extended", "Opus PR text",
                 "tasks without completed runs (sum over cells)"], rader) + [""]
    L += ["Main measure without flagged tasks (`hovedmaal_uten_flaggede`):", ""]
    hu = reg.get("hovedmaal_uten_flaggede", {})
    L += tabell(["arm", "tasks", "runs", "solved share", "interval per task", "interval clustered"],
                [[a, hu[f"{a}|utvidet"]["oppgaver"], hu[f"{a}|utvidet"]["kjoringer"], f4(hu[f"{a}|utvidet"]["loest_andel"]),
                  iv(hu[f"{a}|utvidet"]["intervall_per_oppgave"]), iv(hu[f"{a}|utvidet"]["intervall_klynget_repo"])]
                 for a in ARMER if f"{a}|utvidet" in hu]) + [""]
    flagg = reg["inndelt"].get("flagget_uavhengig", {})
    L += [f"Groups in the flag breakdown: {', '.join(flagg)} (`ja` = flagged, `nei` = not flagged).", ""]
    utenk = {k: v["oppgaver_uten_gjennomforte_kjoringer"]["antall"] for k, v in h.items()}
    L += [f"Tasks without completed runs, per arm and text variant: "
          + ", ".join(f"{k.replace('|', ', ')} {n}" for k, n in utenk.items()) + ".", ""]

    # 6. Missing runs and supplement
    L += ["## T8. Missing runs (registered; results/p3_registrert.json, field `for_seg`)", ""]
    L += tabell(["pass", "number", "task", "text", "arm", "reason code"],
                [[m["pass"], m["nummer"], kort(m["oppgave"]), VNAVN[m["tekstvariant"]], m["arm"], m["grunn"]]
                 for m in reg["for_seg"]["manglende_kjoringer"]]) + [""]
    fs = reg["for_seg"]["forkastede_forsok"]
    L += [f"Discarded attempts: {fs['antall']} (cost {fs['kostnad_usd']} USD). Incomplete passes: "
          f"{len(reg['for_seg']['ufullstendige_pass'])}.", ""]
    L += ["## T9. The four supplementary runs (data/p3/p3_tillegg.jsonl; AVVIK.md no. 9)", ""]
    L += tabell(["number", "task", "arm", "text", "status", "solved", "cost (USD)", "turns", "wall time (s)", "attempt"],
                [[r["nummer"], kort(r["oppgave"]), r["arm"], VNAVN[r["tekstvariant"]], r["status"], "yes" if r["loest"] else "no",
                  f"{r['total_cost_usd']:.4f}", r["num_turns"], r["veggtid_s"], r["forsok"]] for r in tl]) + [""]
    L += [f"Cost of the supplement (sum of `total_cost_usd`): {sum(r['total_cost_usd'] for r in tl):.6f} USD.", ""]
    L += ["## T10. Registered analysis and supplementary analysis side by side (extended text)", "",
          "Supplementary = rows of `data/p3/p3_kjoringer.jsonl` without the four missing, plus the four rows of "
          "`data/p3/p3_tillegg.jsonl` (`results/p3_med_tillegg_inndata.jsonl`), run through the same locked analysis "
          "(`results/p3_med_tillegg.json`). This is a deviation (AVVIK.md no. 9).", ""]
    rader = []
    for a in ARMER:
        for navn, d in (("registered", reg), ("with supplement (deviation)", til)):
            x = d["hovedtall"]["per_arm_og_variant"][f"{a}|utvidet"]
            rader.append([a, navn, x["oppgaver"], x["kjoringer"], x["loste_kjoringer"], f4(x["loest_andel"]),
                          iv(x["intervall_per_oppgave"]), iv(x["intervall_klynget_repo"]), f4(x.get("kostnad_per_loste_usd")),
                          len(d["for_seg"]["manglende_kjoringer"])])
    L += tabell(["arm", "analysis", "tasks", "runs", "solved runs", "solved share", "interval per task", "interval clustered",
                 "cost per solved task (USD)", "missing runs"], rader) + [""]
    endret = []
    for k in reg["hovedtall"]["per_arm_og_variant"]:
        x, y = reg["hovedtall"]["per_arm_og_variant"][k], til["hovedtall"]["per_arm_og_variant"][k]
        if x["loest_andel"] != y["loest_andel"] or x["kjoringer"] != y["kjoringer"]:
            endret.append(k.replace("|", ", "))
    L += [f"Cells that differ between the two analyses: {', '.join(endret) if endret else 'none'}.", ""]

    # 7. Descriptive additions
    L += ["## T11. Cost in NOK (descriptive, not pre-specified; AVVIK.md no. 11)", "",
          f"Rate: {kurs['kurs']} NOK per USD for {kurs['dato']} (Norges Bank, series {kurs['serie']}; {kurs['url']}; "
          f"retrieved {kurs['hentet_utc']}).", ""]
    rader = []
    for a in ARMER:
        for v in VARIANTER:
            x = h[f"{a}|{v}"]
            c = x.get("kostnad_per_loste_usd")
            rader.append([a, VNAVN[v], f4(x["kostnad_usd"]), f"{x['kostnad_usd'] * kurs['kurs']:.2f}", f4(c),
                          "–" if c is None else f"{c * kurs['kurs']:.2f}"])
    L += tabell(["arm", "text", "total cost (USD)", "total cost (NOK)", "cost per solved task (USD)",
                 "cost per solved task (NOK)"], rader) + [""]
    L += [f"Spent in P3 (all rows): {brukt:.6f} USD = {brukt * kurs['kurs']:.2f} NOK. Supplement: "
          f"{sum(r['total_cost_usd'] for r in tl):.6f} USD = {sum(r['total_cost_usd'] for r in tl) * kurs['kurs']:.2f} NOK.", ""]

    L += ["## T12. Solved runs per task (descriptive, not pre-specified; AVVIK.md no. 11)", "",
          "Solved / completed runs from the registered rows (`data/p3/p3_kjoringer.jsonl`). Passes 1–3 for extended text, "
          "passes 1–2 for PR text. The last column shows the cells the supplement (`data/p3/p3_tillegg.jsonl`) changes.", ""]
    rader = []
    for oid in ider:
        celler, endr = [], []
        for a in ARMER:
            for v in VARIANTER:
                rr = [r for r in g if r["oppgave"] == oid and r["arm"] == a and r["tekstvariant"] == v]
                celler.append(f"{sum(bool(r['loest']) for r in rr)}/{len(rr)}")
                tt = [r for r in tl if r["oppgave"] == oid and r["arm"] == a and r["tekstvariant"] == v and r["status"] == "gjennomfort"]
                if tt:
                    alle = rr + tt
                    endr.append(f"{'Sonnet' if 'sonnet' in a else 'Opus'} {VNAVN[v]}: {sum(bool(r['loest']) for r in alle)}/{len(alle)}")
        rader.append([kort(oid), *celler, "; ".join(endr) or ""])
    L += tabell(["task", "Sonnet extended", "Sonnet PR text", "Opus extended", "Opus PR text", "with supplement"], rader) + [""]

    L += ["## T13. Limits stated in the analysis output (field `grenser`)", ""]
    L += [f"- {x}" for x in reg["grenser"]] + [""]
    (RES / "tabeller.md").write_text("\n".join(L), encoding="utf-8")
    print(RES / "tabeller.md")


if __name__ == "__main__":
    main()
